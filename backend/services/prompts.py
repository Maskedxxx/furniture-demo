# Шаблоны промптов для генерации изображений кухонь

def render_prompt(style: str, facade: str, countertop: str, material: str | None = None, notes: str | None = None) -> str:
    """Промпт для Сценария A: чертёж → фотореалистичный рендер."""
    parts = [
        "Вот чертёж/схема кухни с точными размерами и расположением модулей.",
        "Внимательно изучи КАЖДЫЙ элемент на чертеже и сгенерируй фотореалистичное изображение этой кухни.",
        "",
        "КРИТИЧЕСКИ ВАЖНО — точное соответствие чертежу:",
        "— Посчитай ВСЕ модули на чертеже (верхние и нижние шкафы) и отрази КАЖДЫЙ из них",
        "— Сохрани ТОЧНОЕ количество дверец, ящиков и открытых секций",
        "— Сохрани пропорции ширин модулей относительно друг друга (узкие, широкие, угловые)",
        "— Если на чертеже есть двухъярусные верхние шкафы (основной + антресоль) — покажи оба яруса",
        "— Если видна встроенная техника (ПММ, духовой шкаф, вытяжка, холодильник) — покажи её на своих местах",
        "— Угловые модули, торцевые шкафы, накладные бока — всё должно быть на месте",
        "",
        f"Стиль интерьера: {style}.",
        f"Цвет фасадов: {facade}.",
        f"Столешница: {countertop}.",
    ]
    if material:
        parts.append(f"Материал корпуса: {material}.")
    parts.extend([
        "",
        "Визуальные требования:",
        "— Фотореалистичное качество, как из каталога мебельной фабрики",
        "— Вид с перспективой под углом, чтобы была видна вся кухня целиком",
        "— Естественное освещение + подсветка рабочей зоны под верхними шкафами",
        "— Текстуры материалов: фасады, столешница, фартук, ручки",
        "— Ручки на каждой дверце, фурнитура на ящиках",
        "— НЕ упрощай и НЕ уменьшай количество элементов — каждый модуль с чертежа должен быть виден",
    ])
    if notes:
        parts.append(f"— Дополнительные пожелания: {notes}")
    parts.append("")
    parts.append("Сгенерируй ТОЛЬКО изображение, без текста.")
    return "\n".join(parts)


def countertop_prompt(countertop_name: str) -> str:
    """Промпт для Сценария Б: замена столешницы на фото."""
    return "\n".join([
        "Вот фотография реальной кухни.",
        f"Замени столешницу на: {countertop_name}.",
        "",
        "Требования:",
        "— Замени ТОЛЬКО столешницу, всё остальное оставь без изменений",
        "— Фасады, стены, технику, пол, освещение — не трогай",
        "— Новая столешница должна выглядеть реалистично с правильными тенями и отражениями",
        f"— Материал столешницы: {countertop_name} — передай текстуру и цвет максимально точно",
        "— Сохрани ракурс, перспективу и пропорции фотографии",
        "",
        "Сгенерируй ТОЛЬКО изображение, без текста.",
    ])
